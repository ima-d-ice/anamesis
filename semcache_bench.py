#!/usr/bin/env python3
"""semcache benchmark: evaluate semantic cache hit rate vs exact match.

Runs against a live Anamesis server and sweeps cosine similarity thresholds
to find the optimal value for a support-chatbot / RAG workload.

Workload: real customer questions + paraphrases (positives) and unrelated
questions (negatives). Measures hit rate, false positive rate, LLM calls
saved, and estimated cost savings per threshold.

Embeddings are loaded from pre-computed JSONL files (generated by calling
an embedding worker such as llama.cpp or sentence-transformers).
"""

import argparse
import json
import os
import socket
import statistics
import sys
import time


def encode_resp(*parts: str) -> bytes:
    out = b"*%d\r\n" % len(parts)
    for p in parts:
        raw = p.encode()
        out += b"$%d\r\n" % len(raw) + raw + b"\r\n"
    return out


class RespSocket:
    def __init__(self, sock):
        self.sock = sock
        self.buf = b""

    def read_until(self, marker=b"\r\n"):
        while True:
            idx = self.buf.find(marker)
            if idx != -1:
                line = self.buf[:idx]
                self.buf = self.buf[idx + len(marker):]
                return line
            chunk = self.sock.recv(65536)
            if not chunk:
                raise ConnectionError("connection closed by server")
            self.buf += chunk

    def read_exact(self, n: int):
        while len(self.buf) < n:
            chunk = self.sock.recv(65536)
            if not chunk:
                raise ConnectionError("connection closed by server")
            self.buf += chunk
        data, self.buf = self.buf[:n], self.buf[n:]
        return data

    def command(self, *parts: str) -> bytes:
        self.sock.sendall(encode_resp(*parts))
        head = self.read_until()
        if not head:
            raise ConnectionError("empty reply from server")
        if head.startswith(b"$"):
            if head == b"$-1":
                return None
            payload = self.read_exact(int(head[1:]))
            self.read_exact(2)  # trailing \r\n
            return payload
        return head


def load_jsonl(path):
    items = []
    with open(path) as f:
        for line in f:
            line = line.strip()
            if line:
                items.append(json.loads(line))
    return items


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(
        description="semcache benchmark: sweep semantic thresholds "
                    "and measure hit rate vs exact match.")
    parser.add_argument("--host", default="localhost")
    parser.add_argument("--port", type=int, default=6379)
    parser.add_argument("--data-dir", default="data",
                        help="directory containing positives_with_emb.jsonl and negatives_with_emb.jsonl")
    parser.add_argument("--thresholds", type=str, default="0.70,0.75,0.80,0.85,0.90",
                        help="comma-separated thresholds to sweep")
    parser.add_argument("--top-k", type=int, default=5)
    parser.add_argument("--llm-cost", type=float, default=0.001,
                        help="estimated cost per LLM call in dollars")
    args = parser.parse_args(argv)

    thresholds = [float(t) for t in args.thresholds.split(",")]

    # Load dataset with pre-computed embeddings
    positives = load_jsonl(os.path.join(args.data_dir, "positives_with_emb.jsonl"))
    negatives = load_jsonl(os.path.join(args.data_dir, "negatives_with_emb.jsonl"))

    print(f"Dataset: {len(positives)} cached queries, "
          f"{sum(len(p['paraphrases']) for p in positives)} paraphrase variants, "
          f"{len(negatives)} negatives")
    print()

    results = []
    for threshold in thresholds:
        sock = socket.create_connection((args.host, args.port), timeout=10)
        sock.settimeout(30)
        ls = RespSocket(sock)

        # Preload all cached questions
        for p in positives:
            emb_json = json.dumps(p["embedding"])
            reply = ls.command("SEM.PUT", str(p["namespace"]), p["query"],
                               emb_json, p["response"], "0")
            if reply != b"+OK":
                print(f"  WARNING: SEM.PUT {p['query']} -> {reply}", file=sys.stderr)

        # Test paraphrases (should hit via semantic search)
        hits = 0
        total = 0
        correct_hits = 0  # hit the correct original query
        latencies = []
        for p in positives:
            for para in p["paraphrases"]:
                emb_json = json.dumps(para["embedding"])
                t0 = time.perf_counter()
                reply = ls.command("SEM.SEARCH", str(p["namespace"]), emb_json,
                                   str(threshold), str(args.top_k))
                latencies.append((time.perf_counter() - t0) * 1000.0)
                total += 1
                if reply is not None:
                    try:
                        data = json.loads(reply)
                        if data.get("hit"):
                            hits += 1
                            if data.get("key") == p["query"]:
                                correct_hits += 1
                    except json.JSONDecodeError:
                        pass

        # Test negatives (should miss)
        neg_hits = 0
        neg_total = 0
        for n in negatives:
            emb_json = json.dumps(n["embedding"])
            reply = ls.command("SEM.SEARCH", str(n["namespace"]), emb_json,
                               str(threshold), str(args.top_k))
            neg_total += 1
            if reply is not None:
                try:
                    data = json.loads(reply)
                    if data.get("hit"):
                        neg_hits += 1
                except json.JSONDecodeError:
                    pass

        sock.close()

        precision = hits / total if total else 0.0
        fpr = neg_hits / neg_total if neg_total else 0.0
        recall = hits / total if total else 0.0
        correct_recall = correct_hits / total if total else 0.0
        llm_calls_saved = hits
        cost_saved = llm_calls_saved * args.llm_cost
        avg_lat = statistics.mean(latencies) if latencies else 0.0

        results.append({
            "threshold": threshold,
            "hits": hits,
            "total": total,
            "precision": precision,
            "correct_recall": correct_recall,
            "fpr": fpr,
            "recall": recall,
            "llm_calls_saved": llm_calls_saved,
            "cost_saved_usd": cost_saved,
            "avg_latency_ms": avg_lat,
        })

        print(f"threshold={threshold:.2f}  hits={hits}/{total}  "
              f"precision={precision:.3f}  correct_recall={correct_recall:.3f}  "
              f"fpr={fpr:.3f}  llm_saved={llm_calls_saved}  "
              f"cost_saved=${cost_saved:.4f}  avg_lat={avg_lat:.2f}ms")

    # Recommend best threshold
    print()
    print("=" * 70)
    print("RECOMMENDATION: choose threshold with highest precision at "
          "acceptable recall.")
    best = max(results, key=lambda r: r["precision"])
    print(f"  Best precision: threshold={best['threshold']:.2f}, "
          f"precision={best['precision']:.3f}, "
          f"correct_recall={best['correct_recall']:.3f}, "
          f"fpr={best['fpr']:.3f}")
    print(f"  LLM calls saved per {total} paraphrase queries: {best['llm_calls_saved']}")
    print(f"  Estimated cost saved: ${best['cost_saved_usd']:.4f} "
          f"(at ${args.llm_cost} per LLM call)")
    print(f"  Avg latency: {best['avg_latency_ms']:.2f}ms")
    print("=" * 70)

    return 0


if __name__ == "__main__":
    sys.exit(main())
